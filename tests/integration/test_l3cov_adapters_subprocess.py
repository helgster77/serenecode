class TestSafeSubprocessEnvDebug:
    def test_debug_env_var_prints_keys_to_stderr(
        self,
        monkeypatch: pytest.MonkeyPatch,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        """Lines 74-76: SERENECODE_DEBUG set → key listing printed to stderr."""
        monkeypatch.setenv("SERENECODE_DEBUG", "1")
        env = safe_subprocess_env()
        captured = capsys.readouterr()
        assert isinstance(env, dict)
        assert "[serenecode] subprocess environment keys" in captured.err
        # All env keys should be named in the debug output
        for key in env:
            assert key in captured.err

    def test_no_debug_env_var_prints_nothing(
        self,
        monkeypatch: pytest.MonkeyPatch,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        """Opposite branch: SERENECODE_DEBUG unset → silent."""
        monkeypatch.delenv("SERENECODE_DEBUG", raising=False)
        env = safe_subprocess_env(extra_paths={"PYTHONPATH": "/some/src"})
        captured = capsys.readouterr()
        assert captured.err == ""
        assert env["PYTHONPATH"] == "/some/src"

    def test_debug_with_extra_paths_includes_extra_key(
        self,
        monkeypatch: pytest.MonkeyPatch,
        capsys: pytest.CaptureFixture[str],
    ) -> None:
        """Debug branch with extra_paths: merged key appears in the listing."""
        monkeypatch.setenv("SERENECODE_DEBUG", "yes")
        env = safe_subprocess_env(extra_paths={"MYPYPATH": "/stubs"})
        captured = capsys.readouterr()
        assert env["MYPYPATH"] == "/stubs"
        assert "MYPYPATH" in captured.err


