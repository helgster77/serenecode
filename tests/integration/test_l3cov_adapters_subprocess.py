class TestVerifyCheckables:
    def test_no_messages_yields_verified_finding(self) -> None:
        """Lines 689-696: analyze() returns [] → verified finding."""
        checkable = _FakeCheckable(name="clean_func", messages=[])
        findings: list[SymbolicFinding] = []
        _verify_checkables([checkable], findings, "mod.py")
        assert len(findings) == 1
        assert findings[0].function_name == "clean_func"
        assert findings[0].outcome == "verified"
        assert "clean_func" in findings[0].message
        assert findings[0].duration_seconds >= 0.0

    def test_messages_are_converted_to_findings(self) -> None:
        """Lines 703-704: analyze() returns messages → one finding per message."""
        msgs = [
            _FakeMsg(message="ok", state=_FakeState("CONFIRMED")),
            _FakeMsg(
                message="postcondition violated when calling f(x = -1)",
                state=_FakeState("POST_FAIL"),
            ),
        ]
        checkable = _FakeCheckable(name="flaky_func", messages=msgs)
        findings: list[SymbolicFinding] = []
        _verify_checkables([checkable], findings, "mod.py")
        assert len(findings) == 2
        assert findings[0].outcome == "verified"
        assert findings[1].outcome == "counterexample"
        assert all(f.function_name == "flaky_func" for f in findings)

    def test_analyze_exception_is_classified_error(self) -> None:
        """Lines 707-710: analyze() raises plain error → 'error' finding."""
        checkable = _FakeCheckable(name="broken_func", raises=ValueError("boom"))
        findings: list[SymbolicFinding] = []
        _verify_checkables([checkable], findings, "mod.py")
        assert len(findings) == 1
        assert findings[0].function_name == "broken_func"
        assert findings[0].outcome == "error"
        assert "boom" in findings[0].message

    def test_analyze_exception_solver_limitation_is_unsupported(self) -> None:
        """Exception path with solver-limitation text → 'unsupported'."""
        checkable = _FakeCheckable(
            name="deep_func", raises=RuntimeError("unsupported operation")
        )
        findings: list[SymbolicFinding] = []
        _verify_checkables([checkable], findings, "mod.py")
        assert len(findings) == 1
        assert findings[0].outcome == "unsupported"

    def test_multiple_checkables_all_processed(self) -> None:
        """Loop covers success and failure iterations in one call."""
        ok = _FakeCheckable(name="ok_func", messages=[])
        bad = _FakeCheckable(name="bad_func", raises=ValueError("nope"))
        findings: list[SymbolicFinding] = []
        _verify_checkables([ok, bad], findings, "mod.py")
        assert len(findings) == 2
        assert {f.function_name for f in findings} == {"ok_func", "bad_func"}

    def test_empty_checkables_appends_nothing(self) -> None:
        """Zero-iteration loop branch."""
        findings: list[SymbolicFinding] = []
        result = _verify_checkables([], findings, "mod.py")
        assert result is None
        assert findings == []
