@dataclass
class _FakeCtxFn:
    name: str = "fake_func"


class _FakeCheckable:
    """Mimics CrossHair's ConditionCheckable shape."""

    def __init__(
        self,
        name: str = "fake_func",
        messages: list[Any] | None = None,
        raises: Exception | None = None,
    ) -> None:
        self.ctxfn = _FakeCtxFn(name=name)
        self._messages = messages if messages is not None else []
        self._raises = raises

    def analyze(self) -> list[Any]:
        if self._raises is not None:
            raise self._raises
        return list(self._messages)


@dataclass
class _FakeState:
    name: str


@dataclass
class _FakeMsg:
    message: str = ""
    state: object = None


@dataclass
class _DunderHostDataclass:
    """Module-level dataclass so _is_autogenerated_dunder can find it."""

    x: int = 0


def _make_dunder_checkable() -> _FakeCheckable:
    """Build a checkable that looks like _DunderHostDataclass.__hash__."""
    # Note: the class itself (not an instance) — __qualname__ passed to
    # type() becomes the class's qualname and is not visible on instances.
    fn = type(
        "_Fn",
        (),
        {
            "__qualname__": "_DunderHostDataclass.__hash__",
            "__module__": _DunderHostDataclass.__module__,
            "__name__": "__hash__",
        },
    )
    checkable = _FakeCheckable(name="__hash__")
    checkable.ctxfn.fn = fn  # type: ignore[attr-defined]
    return checkable


