_SOURCE = """\
def target(x):
    if x > 0:
        return 1
    return 0
"""


def _make_node(line_start: int = 1, line_end: int = 4) -> _FunctionNode:
    return _FunctionNode(
        name="target",
        qualified_name="target",
        line_start=line_start,
        line_end=line_end,
        is_method=False,
        class_name=None,
    )


class TestBuildCoverageFindings:
    def test_below_threshold_with_missing_lines_generates_suggestions(self) -> None:
        """Lines 353 and 361: not meets + missing lines → suggestions + fail msg."""
        fc = _FunctionCoverage(
            function=_make_node(),
            total_lines=4,
            executed_lines=frozenset({1, 2}),
            missing_lines=frozenset({3, 4}),
            total_branches=2,
            executed_branches=((2, 3),),
            missing_branches=((2, 4),),
        )
        findings = _build_coverage_findings([fc], _SOURCE, "mod.py", 80.0)
        assert len(findings) == 1
        finding = findings[0]
        assert finding.meets_threshold is False
        assert "2 lines uncovered" in finding.message
        assert finding.line_coverage_percent == 50.0
        assert finding.uncovered_lines == (3, 4)
        # Suggestions were generated for the uncovered block
        assert len(finding.suggestions) > 0

    def test_below_threshold_without_missing_lines_has_no_suggestions(self) -> None:
        """Branch 352->355 (false side): branch-only failure → no suggestions."""
        fc = _FunctionCoverage(
            function=_make_node(),
            total_lines=4,
            executed_lines=frozenset({1, 2, 3, 4}),
            missing_lines=frozenset(),
            total_branches=2,
            executed_branches=(),
            missing_branches=((2, 3), (2, 4)),
        )
        findings = _build_coverage_findings([fc], _SOURCE, "mod.py", 80.0)
        assert len(findings) == 1
        finding = findings[0]
        assert finding.meets_threshold is False
        assert finding.suggestions == ()
        assert "0 lines uncovered" in finding.message
        assert finding.branch_coverage_percent == 0.0

    def test_meets_threshold_uses_success_message(self) -> None:
        """Opposite branch (line 355-359): meets → success-style message."""
        fc = _FunctionCoverage(
            function=_make_node(),
            total_lines=4,
            executed_lines=frozenset({1, 2, 3, 4}),
            missing_lines=frozenset(),
            total_branches=0,
            executed_branches=(),
            missing_branches=(),
        )
        findings = _build_coverage_findings([fc], _SOURCE, "mod.py", 80.0)
        assert len(findings) == 1
        finding = findings[0]
        assert finding.meets_threshold is True
        assert "uncovered" not in finding.message
        assert finding.line_coverage_percent == 100.0
        assert finding.branch_coverage_percent == 100.0

    def test_empty_input_returns_empty_list(self) -> None:
        """Loop-exit branch with zero iterations."""
        findings = _build_coverage_findings([], _SOURCE, "mod.py", 80.0)
        assert findings == []


